const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.join(__dirname,"../src/project0553");
const text=f=>fs.readFileSync(path.join(root,f),"utf8");
const assignments=JSON.parse(text("data/vendorDatasheetAssignments0553.json"));
const companies=JSON.parse(text("data/companyMaster0553.json"));
const unified=text("data/vendorUnifiedCatalog0553.js");
const source=text("vendorEvidence.js"),external=text("data/vendorExternalEvidence0553.js");
const ui=text("VendorProductCatalog0553.jsx");
const mgw=text("data/mgwP26058.js");
const management=text("data/rfiLnaPriceDecision0553.js");
assert.deepEqual(assignments.records.map(x=>x.id).sort(),["V-DATO-WEIDMULLER-DS","V-RFI-LNA"].sort());
assert.equal(new Set(assignments.records.map(x=>x.id)).size,2);
const weid=assignments.records.find(x=>x.id==="V-DATO-WEIDMULLER-DS");
assert.equal(weid.company,"RS Thailand");
assert.equal(weid.manufacturer,"Weidmüller");
assert.equal(weid.mr,"MR-0001");
assert.equal(weid.partNumber,"IE-PS-RJ45-FH-BK");
assert(weid.technicalFeatures.ip==="IP20");
assert(weid.relatedRetailEvidenceId==="WEB-RS-WEIDMULLER-1963600000");
assert(external.includes('id:"WEB-RS-WEIDMULLER-1963600000"'));
assert(external.includes('supplier:"RS Thailand"'));
assert(external.includes('unitPrice:1176.68')&&external.includes('budgetPostingAllowed:false'));
const lna=assignments.records.find(x=>x.id==="V-RFI-LNA");
assert.equal(lna.company,"MGW Technologies Pte Ltd");
assert(lna.manufacturer.startsWith("RFI"));
assert.equal(lna.mr,"MR-0002");
assert.equal(lna.partNumber,"RX3852-2002-11");
assert(lna.companyRelationship.includes("NOT_MGW_QUOTED"));
assert(management.includes("unitBudgetAllowance:500000")&&management.includes("vendorQuoted:false"));
assert(mgw.includes('vendor:"MGW Technologies Pte Ltd"'));
assert(!mgw.includes('"RX3852-2002-11"'),"MGW quote must not be presented as RFI LNA offer");
assert(source.includes('id:"V-RFI-LNA",mr:"MR-0002"'));
assert(source.includes('id:"V-DATO-WEIDMULLER-DS",mr:"MR-0001",supplier:"RS Thailand"'));
assert(companies.companies.some(x=>x.id==="rs thailand"&&x.approvedAVL===false));
assert(companies.companies.some(x=>x.id==="mgw technologies pte ltd"&&x.approvedAVL===false));
assert(unified.includes('DATASHEET_ASSIGNMENTS.records'));
assert(unified.includes('VENDOR_0553_SOURCES.find(s=>s.id===mapping.id)'));
assert(unified.includes('quoteId:null,quotation:null,originalQuoteId:null,quantity:null,unitPrice:null'));
assert(unified.includes('referenceFrom:"bid.vendor.products.datasheet."+source.id'));
assert(!ui.includes('Product Datasheets (no quotation recorded)'),"Duplicate datasheet group still shown");
assert(!ui.includes("dataSheetProducts"),"Old datasheet projection still used");
assert(ui.includes('r.sourceClass==="DATASHEET_ONLY"?"bid.vendor.products.datasheet."+r.id'));
assert(ui.includes('Manufacturer: {r.manufacturer}'));
assert(ui.includes('Source / assignment: {r.sourceSupplierLabel}'));
assert(ui.includes('relatedRetailEvidenceId')&&ui.includes('relatedBudgetBasis'));
assert(ui.includes('grouped.map(g=><SmartDataGroup'),"Main supplier grouped view must remain");
assert(assignments.records.every(x=>x.approvalStatus!=="APPROVED"));
console.log("PASS: V-DATO-WEIDMULLER-DS under RS Thailand and V-RFI-LNA under MGW; original IDs, manufacturer roles, reference prices and MGW non-quoted status preserved; standalone datasheet display removed.");
