const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const root=path.join(__dirname,"../src");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const common=read("common/ui/SmartDataExplorer.jsx");
const docs=read("project0553/ParticularRequirementMatrix0553.jsx");
const vendor=read("project0553/VendorProductCatalog0553.jsx");
const bom=read("project0553/SimpleBom0553.jsx");
const tags=read("common/ui/ComponentCopyId.jsx");
const terms=read("project0553/QuotationTermsDetail0553.jsx");
const quote=JSON.parse(read("project0553/data/quotes/NG-260916-ADV-DAP1.full.json"));
for(const name of ["SmartFilterBar","SmartDataGroup","moduleSegment"])assert(common.includes("export "+(name==="moduleSegment"?"const ":"function ")+name),"shared component "+name+" missing");
assert(common.includes("onReset")&&common.includes("total")&&common.includes("shown"));
assert(common.includes("componentKey={moduleKey}"),"Grouped module ID copy missing");
assert(tags.includes('const value=projectId+" / "+componentKey'),"Canonical full copy ID changed");
assert(docs.includes('<SmartFilterBar')&&docs.includes('groupedRows.map(group=><SmartDataGroup'),"Documents smart group missing");
assert(docs.includes("particular-requirement-matrix.rule."),"Requirement line Copy ID missing");
assert(vendor.includes('<SmartFilterBar')&&vendor.includes('grouped.map(g=><SmartDataGroup'),"Vendor smart group missing");
assert(vendor.includes("bid.vendor.products.quote-line."),"Existing vendor line module identity broken");
assert(vendor.includes("bid.vendor.products.quotation-selector"),"Quotation selector Copy ID missing");
assert(vendor.includes("<QuotationTermsDetail0553 quote={selectedCommercial}/>")&&vendor.includes("<QuotationTermsDetail0553 quote={q.header}/>"),"Quotation conditions must render in both selected quotation and grouped view");
assert(terms.includes("commercialTerms?.sourceTermRecords")&&terms.includes("Original supplier commercial wording (preserved)")&&terms.includes("Source Page"),"Source quotation term details and original wording must remain traceable");
assert(quote.quoteNumber==="NG/260916-ADV-DAP1"&&quote.quotedLineCount===53&&quote.quotedGrandTotal===191610.15,"Original Next G quote identity, 53 lines and original total must remain intact");
assert(vendor.includes("EXION_LATEST"),"Latest EXION quote missing");
assert(bom.includes('moduleKey="bid.budget.bom.module-search"'),"BOM module search missing");
assert(bom.includes('moduleKey="bid.budget.bom.filters"'),"BOM faceted filter missing");
assert(bom.includes("componentKey={m.id}"),"BOM navigator missing Copy ID");
assert(bom.includes('<LocationBomDetail0553 site={g.site}'),"BOM drilldown removed");
assert(bom.includes("getMR0001LocationCost0553"),"Cost ledger read removed");
assert(!common.includes("unitPrice")&&!common.includes("extendedCost"),"Shared visual component must not recalculate cost");
console.log("PASS 0553 Smart Data Explorer: shared filters/groups, copyable module IDs, current documents/vendor/BOM bindings.");
